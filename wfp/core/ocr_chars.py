"""文字認識(OCR)の読み違いをそろえる表(core.text の fold_ocr・ocr_key と wfportal_msscan の ms_key が使う)。

const(URL・ファイル名・機能の設定と表示名)とは用途が違うので分けて置く(2026-11-09 利用者の指定)。wfp の他のモジュールは import しない。
読み取りの画面ごとの調整(wfportal_msscan の MSSCAN_KANJI_LATIN・wfportal_rivenscan の符号の読み違いなど)はそのファイルの頭に置く
"""
from __future__ import annotations

# 長音記号のように使われる横棒(半角の - を含む)。fold_ocr では消し、ocr_key では「ー」にそろえる
OCR_DASHES = "-‐－―"

# 濁点・半濁点を取ったあとの小さいかなと、カタカナに似た漢字(OCR がよく取り違える)
OCR_KANA_FOLD = {"ァ": "ア", "ィ": "イ", "ゥ": "ウ", "ェ": "エ", "ォ": "オ", "ャ": "ヤ", "ュ": "ユ", "ョ": "ヨ",
                 "ッ": "ツ", "ヮ": "ワ", "ぁ": "あ", "ぃ": "い", "ぅ": "う", "ぇ": "え", "ぉ": "お",
                 "ゃ": "や", "ゅ": "ゆ", "ょ": "よ", "っ": "つ",
                 "工": "エ", "口": "ロ", "力": "カ", "夕": "タ", "卜": "ト", "二": "ニ", "八": "ハ"}

# 英数字の取り違えやすい文字(0/o・1/l/i・5/s など。ocr_key は小文字にしてからかける)
OCR_CONFUSE = {"0": "o", "1": "l", "i": "l", "|": "l", "5": "s", "8": "b", "$": "s"}

# ocr_key で残す文字(正規表現の文字クラスの中身): 英数字・&・かな・漢字。ほかの記号・空白は消す
OCR_KEY_KEEP = r"a-z0-9&\u3040-\u30ff\u4e00-\u9fff"

# 大文字の I の読み違い(ms_key が ocr_key の前に l にする。記号として消されると「LOKI」が「lok」になる)
OCR_LIKE_L = {"|": "l", "!": "l", "｜": "l", "！": "l"}
